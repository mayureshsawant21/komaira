create or replace function shop.is_admin() returns boolean
language sql stable security definer set search_path = shop, pg_temp as $$
  select auth.uid() is not null and exists (select 1 from shop.admins where user_id = auth.uid())
$$;

create or replace function shop.require_admin() returns void
language plpgsql stable security definer set search_path = shop, pg_temp as $$
begin
  if not shop.is_admin() then
    raise exception 'Not authorised. Please sign in with an admin account.' using errcode = '42501';
  end if;
end $$;

create or replace function shop.setting(k text) returns text
language sql stable security definer set search_path = shop, pg_temp as $$
  select coalesce((select value from shop.settings where key = k), '')
$$;

create or replace function shop.setting_int(k text) returns int
language sql stable security definer set search_path = shop, pg_temp as $$
  select case when shop.setting(k) ~ '^\s*-?\d+\s*$' then shop.setting(k)::int else 0 end
$$;

create or replace function shop.ist_today() returns date
language sql stable as $$ select (now() at time zone 'Asia/Kolkata')::date $$;

-- Start of the day N-1 days ago (India time), so since_days(1) = start of today.
create or replace function shop.since_days(n int) returns timestamptz
language sql stable as $$ select ((shop.ist_today() - (greatest(n, 1) - 1))::timestamp at time zone 'Asia/Kolkata') $$;

create or replace function shop.slugify(t text) returns text
language sql immutable as $$
  select coalesce(nullif(left(trim(both '-' from regexp_replace(replace(lower(coalesce(t, '')), '&', ' and '), '[^a-z0-9]+', '-', 'g')), 80), ''), 'item')
$$;

create or replace function shop.unique_slug(tbl text, base text, except_id bigint default 0) returns text
language plpgsql security definer set search_path = shop, pg_temp as $$
declare
  root text := shop.slugify(base);
  candidate text := root;
  n int := 2;
  taken boolean;
begin
  loop
    execute format('select exists (select 1 from shop.%I where slug = $1 and id <> $2)', tbl) into taken using candidate, coalesce(except_id, 0);
    exit when not taken;
    candidate := root || '-' || n;
    n := n + 1;
  end loop;
  return candidate;
end $$;

-- Only allow store links (#/…, /…) and http(s) URLs in admin-entered links.
create or replace function shop.safe_link(l text) returns text
language sql immutable as $$
  select case
    when nullif(trim(coalesce(l, '')), '') is null then null
    when trim(l) ~* '^https?://' then trim(l)
    when trim(l) like '#/%' then trim(l)
    when trim(l) like '/%' and trim(l) not like '//%' then '#' || trim(l)
    else '#/' || regexp_replace(trim(l), '^[#/]+', '')
  end
$$;

create or replace function shop.txt(v text, max_len int default 500) returns text
language sql immutable as $$ select nullif(left(trim(coalesce(v, '')), max_len), '') $$;

create or replace function shop.paise(v jsonb) returns int
language sql immutable as $$
  select case
    when v is null or jsonb_typeof(v) = 'null' then null
    when jsonb_typeof(v) = 'number' then round((v #>> '{}')::numeric)::int
    when trim(v #>> '{}') ~ '^\d+$' then (v #>> '{}')::int
    else null end
$$;

-- Everything a product card needs, with live stock and rating.
create or replace view shop.product_cards as
select p.*,
  c.name as category_name,
  c.slug as category_slug,
  (select url from shop.product_images i where i.product_id = p.id order by sort_order, id limit 1) as image,
  (select url from shop.product_images i where i.product_id = p.id order by sort_order, id limit 1 offset 1) as image2,
  (select round(avg(rating), 1) from shop.reviews r where r.product_id = p.id and r.status = 'approved') as rating,
  (select count(*)::int from shop.reviews r where r.product_id = p.id and r.status = 'approved') as review_count,
  (select count(*)::int from shop.product_variants v where v.product_id = p.id) as variant_count,
  (select min(coalesce(v.price, p.price)) from shop.product_variants v where v.product_id = p.id) as min_variant_price,
  case when exists (select 1 from shop.product_variants v where v.product_id = p.id)
    then (select coalesce(sum(stock), 0)::int from shop.product_variants v where v.product_id = p.id)
    else p.stock end as available,
  (select coalesce(sum(oi.quantity), 0)::int from shop.order_items oi join shop.orders o on o.id = oi.order_id
    where oi.product_id = p.id and o.status <> 'cancelled') as sold
from shop.products p
left join shop.categories c on c.id = p.category_id;

