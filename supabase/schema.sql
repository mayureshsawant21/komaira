    'daily', (select jsonb_agg(jsonb_build_object('day', d.day, 'visitors', coalesce(v.visitors, 0), 'revenue', coalesce(r.revenue, 0)) order by d.day)
      from (select (shop.ist_today() - g)::date as day from generate_series(0, 29) g) d
      left join (select (created_at at time zone 'Asia/Kolkata')::date as day, count(distinct visitor_id) as visitors
        from shop.page_views where created_at >= since30 group by 1) v on v.day = d.day
      left join (select (created_at at time zone 'Asia/Kolkata')::date as day, sum(total) as revenue from shop.orders
        where created_at >= since30 and status <> 'cancelled' and (payment_method = 'cod' or payment_status = 'paid') group by 1) r on r.day = d.day),
    'recent_orders', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'order_number', order_number, 'name', name, 'total', total,
      'status', status, 'payment_method', payment_method, 'payment_status', payment_status, 'created_at', created_at) order by created_at desc)
