create or replace function shop.filtered_products(p jsonb) returns setof shop.product_cards
language plpgsql stable security definer set search_path = shop, pg_temp as $$
declare
  cat_ids bigint[];
  q text := nullif(trim(coalesce(p->>'q', '')), '');
begin
  if nullif(p->>'category', '') is not null then
    with recursive tree(id) as (
      select id from shop.categories where slug = p->>'category'
      union all
      select c.id from shop.categories c join tree t on c.parent_id = t.id
    ) select coalesce(array_agg(id), '{}') into cat_ids from tree;
  end if;
  if q is not null then
    q := '%' || replace(replace(replace(left(q, 80), '\', '\\'), '%', '\%'), '_', '\_') || '%';
  end if;
  return query
    select * from shop.product_cards pc
    where pc.status = 'active'
      and (cat_ids is null or pc.category_id = any (cat_ids))
      and (q is null or pc.name ilike q or pc.brand ilike q or pc.tags ilike q or pc.short_description ilike q or pc.category_name ilike q)
      and (shop.paise(p->'min') is null or pc.price >= shop.paise(p->'min'))
      and (shop.paise(p->'max') is null or pc.price <= shop.paise(p->'max'))
      and (coalesce((p->>'inStock')::boolean, false) = false or pc.available > 0)
      and (coalesce((p->>'onSale')::boolean, false) = false or pc.compare_at_price > pc.price)
      and (coalesce((p->>'featured')::boolean, false) = false or pc.is_featured)
      and (nullif(p->>'exclude', '') is null or pc.id <> (p->>'exclude')::bigint);
end $$;

create or replace function shop.eval_coupon(code_in text, subtotal int) returns jsonb
language plpgsql stable security definer set search_path = shop, pg_temp as $$
declare c shop.coupons; d int;
begin
  if nullif(trim(coalesce(code_in, '')), '') is null then return jsonb_build_object('discount', 0); end if;
  select * into c from shop.coupons where lower(code) = lower(trim(code_in)) and is_active;
  if not found then return jsonb_build_object('discount', 0, 'error', 'That coupon code is not valid.'); end if;
  if c.starts_at is not null and c.starts_at > shop.ist_today() then return jsonb_build_object('discount', 0, 'error', 'This coupon is not active yet.'); end if;
  if c.ends_at is not null and c.ends_at < shop.ist_today() then return jsonb_build_object('discount', 0, 'error', 'This coupon has expired.'); end if;
  if c.max_uses is not null and c.used_count >= c.max_uses then return jsonb_build_object('discount', 0, 'error', 'This coupon has reached its usage limit.'); end if;
  if subtotal < c.min_order then
    return jsonb_build_object('discount', 0, 'error',
      format('Add items worth %s%s more to use this coupon.', shop.setting('currency_symbol'), ceil((c.min_order - subtotal) / 100.0)::int));
  end if;
  d := case when c.type = 'percent' then round(subtotal * least(c.value, 100) / 100.0)::int else least(c.value, subtotal) end;
  return jsonb_build_object('discount', d, 'coupon_id', c.id, 'code', c.code);
end $$;

create or replace function shop.shipping_for(amount int) returns int
language sql stable security definer set search_path = shop, pg_temp as $$
  select case
    when amount <= 0 then 0
    when shop.setting_int('free_shipping_threshold') > 0 and amount >= shop.setting_int('free_shipping_threshold') then 0
    else shop.setting_int('shipping_fee') end
$$;

create or replace function shop.order_json(oid bigint, include_private boolean default false) returns jsonb
language sql stable security definer set search_path = shop, pg_temp as $$
  select (to_jsonb(o) - case when include_private then '{}'::text[] else array['admin_notes'] end)
    || jsonb_build_object(
