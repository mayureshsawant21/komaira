begin
  perform shop.require_admin();
  o := shop.order_json((p->>'id')::bigint, true);
  if o is null then return null; end if;
  return o || jsonb_build_object('customer_orders',
    case when o->>'customer_id' is not null then (select count(*) from shop.orders where customer_id = (o->>'customer_id')::uuid) end);
end $$;

-- p: { id, status, payment_status, courier, tracking_number, admin_notes, note }
create or replace function public.admin_update_order(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = shop, pg_temp as $$
declare
  o shop.orders;
  new_status text;
  new_pay text;
begin
  perform shop.require_admin();
  select * into o from shop.orders where id = (p->>'id')::bigint for update;
  if not found then raise exception 'Order not found.' using errcode = 'P0001'; end if;
  new_status := case when p->>'status' in ('pending', 'confirmed', 'processing', 'shipped', 'delivered', 'cancelled') then p->>'status' else o.status end;
  new_pay := case when p->>'payment_status' in ('pending', 'paid', 'failed', 'refunded') then p->>'payment_status' else o.payment_status end;
  update shop.orders set courier = shop.txt(p->>'courier', 80), tracking_number = shop.txt(p->>'tracking_number', 80),
    admin_notes = shop.txt(p->>'admin_notes', 2000), payment_status = new_pay, payment_ref = coalesce(shop.txt(p->>'payment_ref', 100), payment_ref),
    updated_at = now()
  where id = o.id;
  if new_pay <> o.payment_status then
    insert into shop.order_events (order_id, status, note) values (o.id, o.status, 'Payment marked ' || new_pay);
  end if;
  if new_status <> o.status then
    if new_status = 'cancelled' then perform shop.restock(o.id); end if;
    if o.status = 'cancelled' then perform shop.take_stock(o.id); end if;
    update shop.orders set status = new_status where id = o.id;
    insert into shop.order_events (order_id, status, note) values (o.id, new_status, shop.txt(p->>'note', 300));
  end if;
  return shop.order_json(o.id, true);
end $$;

