create or replace function public.store_bootstrap(p jsonb default '{}') returns jsonb
language sql stable security definer set search_path = shop, pg_temp as $$
  select jsonb_build_object(
    'settings', (select jsonb_object_agg(key, value) from shop.settings where key not in ('order_notify_email')),
    'categories', coalesce((
      select jsonb_agg(jsonb_build_object('id', c.id, 'parent_id', c.parent_id, 'name', c.name, 'slug', c.slug,
        'description', c.description, 'image', c.image, 'show_on_home', c.show_on_home,
        'product_count', (select count(*) from shop.products x where x.category_id = c.id and x.status = 'active'))
        order by c.sort_order, c.name)
      from shop.categories c where c.is_active), '[]'),
    'pages', coalesce((select jsonb_agg(jsonb_build_object('slug', slug, 'title', title) order by id)
      from shop.pages where is_active and show_in_footer), '[]'))
$$;

create or replace function public.home_data(p jsonb default '{}') returns jsonb
language sql stable security definer set search_path = shop, pg_temp as $$
  select jsonb_build_object(
    'banners', coalesce((select jsonb_agg(to_jsonb(b) order by b.sort_order, b.id) from shop.banners b
      where b.is_active and (b.starts_at is null or b.starts_at <= now()) and (b.ends_at is null or b.ends_at >= now())), '[]'),
    'featured', coalesce((select jsonb_agg(shop.card_json(x)) from (
      select * from shop.filtered_products('{"featured": true}') order by created_at desc limit 8) x), '[]'),
    'newest', coalesce((select jsonb_agg(shop.card_json(x)) from (
      select * from shop.filtered_products('{}') order by created_at desc limit 8) x), '[]'),
    'on_sale', coalesce((select jsonb_agg(shop.card_json(x)) from (
      select * from shop.filtered_products('{"onSale": true}') order by created_at desc limit 4) x), '[]'),
    'reviews', coalesce((select jsonb_agg(jsonb_build_object('name', r.name, 'rating', r.rating, 'body', r.body,
        'product_name', pr.name, 'product_slug', pr.slug) order by r.created_at desc)
      from (select * from shop.reviews where status = 'approved' and rating >= 4 order by created_at desc limit 3) r
      join shop.products pr on pr.id = r.product_id and pr.status = 'active'), '[]'))
$$;

-- p: { category, q, min, max (paise), sort, inStock, onSale, featured, exclude, limit, offset }
create or replace function public.list_products(p jsonb default '{}') returns jsonb
language plpgsql stable security definer set search_path = shop, pg_temp as $$
declare
  lim int := least(greatest(coalesce((p->>'limit')::int, 12), 1), 60);
  off int := greatest(coalesce((p->>'offset')::int, 0), 0);
  srt text := coalesce(p->>'sort', 'featured');
  total int;
  items jsonb;
  cat jsonb;
begin
  select count(*) into total from shop.filtered_products(p);
  select coalesce(jsonb_agg(shop.card_json(x.f) order by x.rn), '[]') into items from (
    select f, row_number() over (order by
      case when srt = 'price_asc' then f.price end asc,
      case when srt = 'price_desc' then f.price end desc,
      case when srt = 'name' then lower(f.name) end asc,
      case when srt = 'newest' then f.created_at end desc,
      case when srt = 'popular' then f.sold end desc,
      f.is_featured desc, f.created_at desc, f.id) as rn
    from shop.filtered_products(p) f
    order by rn limit lim offset off) x;
  if nullif(p->>'category', '') is not null then
    select jsonb_build_object('id', c.id, 'name', c.name, 'slug', c.slug, 'description', c.description,
      'parent', (select jsonb_build_object('name', pc.name, 'slug', pc.slug) from shop.categories pc where pc.id = c.parent_id),
      'children', coalesce((select jsonb_agg(jsonb_build_object('name', s.name, 'slug', s.slug) order by s.sort_order, s.name)
        from shop.categories s where s.parent_id = c.id and s.is_active), '[]'))
    into cat from shop.categories c where c.slug = p->>'category' and c.is_active;
  end if;
  return jsonb_build_object('items', items, 'total', total, 'category', cat);
end $$;

