end $$;

-- =============================================================================
-- Owner-only: run in the SQL Editor to make an existing user an admin, e.g.
--   select make_admin('you@example.com', 'Your Name');
-- Not callable from the website.
-- =============================================================================
create or replace function public.make_admin(user_email text, display_name text default null) returns text
language plpgsql volatile security definer set search_path = shop, pg_temp as $$
declare u record;
begin
  select id, email into u from auth.users where lower(email) = lower(trim(user_email));
  if not found then
    return 'No user with that email. Create it first: Authentication → Users → Add user (tick "Auto Confirm User").';
  end if;
  insert into shop.admins (user_id, name, email) values (u.id, coalesce(display_name, u.email), u.email)
  on conflict (user_id) do update set name = coalesce(display_name, shop.admins.name);
  return u.email || ' is now an admin.';
end $$;
revoke execute on function public.make_admin(text, text) from public;
