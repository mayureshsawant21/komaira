-- value: percent (e.g. 10) for 'percent', paise for 'fixed'; min_order in paise; dates YYYY-MM-DD.
create or replace function public.admin_save_coupon(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = shop, pg_temp as $$
declare
  cid bigint := nullif(p->>'id', '')::bigint;
  cd text := upper(regexp_replace(coalesce(p->>'code', ''), '[^A-Za-z0-9_-]', '', 'g'));
  typ text := case when p->>'type' = 'fixed' then 'fixed' else 'percent' end;
  val int := coalesce(shop.paise(p->'value'), 0);
begin
  perform shop.require_admin();
  if typ = 'percent' then val := least(val, 100); end if;
  if cd = '' then raise exception 'Coupon code is required (letters and numbers).' using errcode = 'P0001'; end if;
  if val <= 0 then raise exception 'Discount value must be more than zero.' using errcode = 'P0001'; end if;
  if exists (select 1 from shop.coupons where lower(code) = lower(cd) and id <> coalesce(cid, 0)) then
    raise exception 'That code already exists.' using errcode = 'P0001';
  end if;
  if cid is null then
    insert into shop.coupons (code, value) values (cd, val) returning id into cid;
  end if;
  update shop.coupons set code = left(cd, 30), description = shop.txt(p->>'description', 200), type = typ, value = val,
    min_order = coalesce(shop.paise(p->'min_order'), 0),
    max_uses = case when coalesce(p->>'max_uses', '') ~ '^\d+$' then (p->>'max_uses')::int end,
    starts_at = case when coalesce(p->>'starts_at', '') ~ '^\d{4}-\d{2}-\d{2}$' then (p->>'starts_at')::date end,
    ends_at = case when coalesce(p->>'ends_at', '') ~ '^\d{4}-\d{2}-\d{2}$' then (p->>'ends_at')::date end,
    is_active = coalesce((p->>'is_active')::boolean, true)
  where id = cid;
  return jsonb_build_object('id', cid);
end $$;

