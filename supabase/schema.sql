-- Returns { id, removed_image }.
create or replace function public.admin_save_category(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = shop, pg_temp as $$
declare
  cid bigint := nullif(p->>'id', '')::bigint;
  existing shop.categories;
  nm text := shop.txt(p->>'name', 100);
  parent bigint := nullif(p->>'parent_id', '')::bigint;
  cur bigint;
  slug_in text := shop.txt(p->>'slug', 100);
begin
  perform shop.require_admin();
