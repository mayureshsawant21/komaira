create or replace function shop.restock(oid bigint) returns void
language plpgsql security definer set search_path = shop, pg_temp as $$
declare it record;
begin
  for it in select * from shop.order_items where order_id = oid loop
    if it.variant_id is not null then
      update shop.product_variants set stock = stock + it.quantity where id = it.variant_id;
    elsif it.product_id is not null then
      update shop.products set stock = stock + it.quantity where id = it.product_id;
    end if;
  end loop;
end $$;

create or replace function shop.take_stock(oid bigint) returns void
language plpgsql security definer set search_path = shop, pg_temp as $$
declare it record; n int;
begin
  for it in select * from shop.order_items where order_id = oid loop
    if it.variant_id is not null then
      update shop.product_variants set stock = stock - it.quantity where id = it.variant_id and stock >= it.quantity;
    elsif it.product_id is not null then
      update shop.products set stock = stock - it.quantity where id = it.product_id and stock >= it.quantity;
    else
      continue;
    end if;
    get diagnostics n = row_count;
    if n <> 1 then
      raise exception 'Not enough stock of % to re-open this order.', it.name using errcode = 'P0001';
    end if;
  end loop;
end $$;

