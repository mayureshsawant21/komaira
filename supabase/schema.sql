-- p: product fields + variants: [{id, name, sku, price, stock, color}] + images: [{url, alt}] (in display order)
-- Returns { id, slug, removed_images: [urls no longer used] }.
create or replace function public.admin_save_product(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = shop, pg_temp as $$
declare
  pid bigint := nullif(p->>'id', '')::bigint;
  existing shop.products;
  nm text := shop.txt(p->>'name', 200);
  v_price int := shop.paise(p->'price');
  v_compare int := shop.paise(p->'compare_at_price');
  new_vid bigint;
  slug_in text := shop.txt(p->>'slug', 100);
  new_slug text;
  v jsonb;
  i int := 0;
  keep_ids bigint[] := '{}';
  removed jsonb;
begin
  perform shop.require_admin();
  if nm is null then raise exception 'Product name is required.' using errcode = 'P0001'; end if;
  if v_price is null then raise exception 'Price is required.' using errcode = 'P0001'; end if;
  if v_compare is not null and v_compare <= v_price then
    raise exception 'MRP / compare-at price should be higher than the selling price — or leave it blank.' using errcode = 'P0001';
  end if;
  if pid is not null then
    select * into existing from shop.products where id = pid;
    if not found then raise exception 'Product not found.' using errcode = 'P0001'; end if;
  end if;
  new_slug := case when existing.id is not null and (slug_in is null or slug_in = existing.slug) then existing.slug
                   else shop.unique_slug('products', coalesce(slug_in, nm), coalesce(pid, 0)) end;

  if pid is null then
    insert into shop.products (name, slug) values (nm, new_slug) returning id into pid;
  end if;
  update shop.products set
    name = nm, slug = new_slug,
    category_id = (select id from shop.categories where id = nullif(p->>'category_id', '')::bigint),
    sku = shop.txt(p->>'sku', 64), brand = shop.txt(p->>'brand', 100),
    short_description = shop.txt(p->>'short_description', 500), description = shop.txt(p->>'description', 20000),
    ingredients = shop.txt(p->>'ingredients', 5000), how_to_use = shop.txt(p->>'how_to_use', 5000),
    size = shop.txt(p->>'size', 60), skin_type = shop.txt(p->>'skin_type', 120),
    tags = (select nullif(string_agg(trim(t), ', '), '') from unnest(string_to_array(coalesce(p->>'tags', ''), ',')) t where trim(t) <> ''),
    badge = shop.txt(p->>'badge', 30), price = v_price, compare_at_price = v_compare,
    stock = greatest(coalesce((p->>'stock')::int, 0), 0),
    low_stock_threshold = greatest(coalesce((p->>'low_stock_threshold')::int, 5), 0),
    variant_label = shop.txt(p->>'variant_label', 40),
    is_featured = coalesce((p->>'is_featured')::boolean, false),
    status = case when p->>'status' = 'draft' then 'draft' else 'active' end,
    meta_title = shop.txt(p->>'meta_title', 120), meta_description = shop.txt(p->>'meta_description', 300),
    updated_at = now()
  where id = pid;

  -- Variants: update the ones sent with an id, add new ones, delete the rest.
  for v in select * from jsonb_array_elements(coalesce(p->'variants', '[]')) loop
    continue when shop.txt(v->>'name', 80) is null;
    if nullif(v->>'id', '') is not null and exists (select 1 from shop.product_variants where id = (v->>'id')::bigint and product_id = pid) then
      update shop.product_variants set name = shop.txt(v->>'name', 80), sku = shop.txt(v->>'sku', 64), price = shop.paise(v->'price'),
        stock = greatest(coalesce((v->>'stock')::int, 0), 0),
        color = case when coalesce(v->>'color', '') ~* '^#[0-9a-f]{6}$' then v->>'color' end, sort_order = i
      where id = (v->>'id')::bigint;
      keep_ids := keep_ids || (v->>'id')::bigint;
    else
      insert into shop.product_variants (product_id, name, sku, price, stock, color, sort_order)
      values (pid, shop.txt(v->>'name', 80), shop.txt(v->>'sku', 64), shop.paise(v->'price'), greatest(coalesce((v->>'stock')::int, 0), 0),
        case when coalesce(v->>'color', '') ~* '^#[0-9a-f]{6}$' then v->>'color' end, i)
      returning id into new_vid;
      keep_ids := keep_ids || new_vid;
    end if;
    i := i + 1;
  end loop;
  delete from shop.product_variants where product_id = pid and not (id = any (keep_ids));

  -- Images: replace with the list sent (in display order).
  select coalesce(jsonb_agg(url), '[]') into removed from shop.product_images
    where product_id = pid and not exists (select 1 from jsonb_array_elements(coalesce(p->'images', '[]')) x where x->>'url' = url);
  delete from shop.product_images where product_id = pid;
  insert into shop.product_images (product_id, url, alt, sort_order)
  select pid, x->>'url', coalesce(shop.txt(x->>'alt', 150), nm), (ord - 1)::int
  from jsonb_array_elements(coalesce(p->'images', '[]')) with ordinality as t(x, ord)
  where coalesce(x->>'url', '') <> '';

  return jsonb_build_object('id', pid, 'slug', new_slug, 'removed_images', removed);
end $$;

