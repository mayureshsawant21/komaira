do $$ begin
  if to_regclass('storage.buckets') is not null then
    insert into storage.buckets (id, name, public) values ('media', 'media', true) on conflict (id) do update set public = true;
    execute 'drop policy if exists "media public read" on storage.objects';
    execute 'drop policy if exists "media admin insert" on storage.objects';
    execute 'drop policy if exists "media admin update" on storage.objects';
    execute 'drop policy if exists "media admin delete" on storage.objects';
    execute $p$create policy "media public read" on storage.objects for select using (bucket_id = 'media')$p$;
    execute $p$create policy "media admin insert" on storage.objects for insert to authenticated with check (bucket_id = 'media' and public.is_admin())$p$;
    execute $p$create policy "media admin update" on storage.objects for update to authenticated using (bucket_id = 'media' and public.is_admin())$p$;
    execute $p$create policy "media admin delete" on storage.objects for delete to authenticated using (bucket_id = 'media' and public.is_admin())$p$;
  end if;
end $$;
