-- p: { items: [{product_id, variant_id, qty}], coupon }
-- Prices every line from the database; drops unavailable lines and clamps quantities to stock.
create or replace function public.cart_quote(p jsonb) returns jsonb
language plpgsql stable security definer set search_path = shop, pg_temp as $$
declare
  e jsonb;
  idx int := -1;
  pr record;
  v shop.product_variants;
  qty int;
  stock_avail int;
  unit int;
  lines jsonb := '[]';
  notices jsonb := '[]';
  subtotal int := 0;
  cpn jsonb;
  discount int;
  shipping int;
  threshold int := shop.setting_int('free_shipping_threshold');
begin
  for e in select * from jsonb_array_elements(coalesce(p->'items', '[]')) loop
    idx := idx + 1;
    exit when idx >= 30;
    select pc.*, (select count(*) from shop.product_variants x where x.product_id = pc.id) as nvar into pr
      from shop.product_cards pc where pc.id = (e->>'product_id')::bigint and pc.status = 'active';
    if not found then
      notices := notices || to_jsonb('An item in your bag is no longer available and was removed.'::text);
      continue;
    end if;
    v := null;
    if pr.nvar > 0 then
      select * into v from shop.product_variants where id = (e->>'variant_id')::bigint and product_id = pr.id;
      if not found then
        notices := notices || to_jsonb(format('Please choose a %s for %s.', lower(coalesce(pr.variant_label, 'option')), pr.name));
        continue;
      end if;
      stock_avail := v.stock;
      unit := coalesce(v.price, pr.price);
    else
      stock_avail := pr.stock;
      unit := pr.price;
    end if;
    if stock_avail <= 0 then
      notices := notices || to_jsonb(format('%s is now out of stock and was removed from your bag.', pr.name));
      continue;
    end if;
    qty := least(greatest(coalesce((e->>'qty')::int, 1), 1), 10);
    if qty > stock_avail then
      qty := stock_avail;
      notices := notices || to_jsonb(format('Only %s left of %s — quantity updated.', stock_avail, pr.name));
    end if;
    lines := lines || jsonb_build_object(
      'product_id', pr.id, 'variant_id', v.id, 'name', pr.name, 'slug', pr.slug, 'image', pr.image,
      'variant_name', v.name, 'variant_label', coalesce(pr.variant_label, 'Option'), 'sku', coalesce(v.sku, pr.sku),
      'price', unit, 'compare_at_price', pr.compare_at_price, 'qty', qty, 'stock', least(stock_avail, 10), 'total', unit * qty);
    subtotal := subtotal + unit * qty;
  end loop;

  cpn := shop.eval_coupon(p->>'coupon', subtotal);
  discount := coalesce((cpn->>'discount')::int, 0);
  shipping := shop.shipping_for(subtotal - discount);
  return jsonb_build_object(
    'lines', lines, 'notices', notices, 'subtotal', subtotal, 'discount', discount,
    'coupon', cpn->>'code', 'coupon_error', cpn->>'error', 'shipping', shipping,
    'total', subtotal - discount + shipping,
    'count', coalesce((select sum((l->>'qty')::int) from jsonb_array_elements(lines) l), 0),
    'free_shipping_threshold', threshold,
    'free_shipping_remaining', case when threshold > 0 and subtotal - discount < threshold then threshold - (subtotal - discount) else 0 end);
end $$;

-- p: { items, coupon, payment_method: 'cod' | 'upi', customer: { name, email, phone, address_line1, address_line2, city, state, pincode, notes } }
create or replace function public.place_order(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = shop, pg_temp as $$
declare
  c jsonb := coalesce(p->'customer', '{}');
  nm text := shop.txt(c->>'name', 100);
  em text := lower(shop.txt(c->>'email', 200));
  ph text := regexp_replace(coalesce(c->>'phone', ''), '[^0-9+]', '', 'g');
  pin text := trim(coalesce(c->>'pincode', ''));
  pm text := p->>'payment_method';
  quote jsonb;
  l jsonb;
  oid bigint;
  onum text;
  tok text := replace(gen_random_uuid()::text, '-', '');
  shipping int;
  n int;
  cpn jsonb;
begin
  if nm is null then raise exception 'Please enter your full name.' using errcode = 'P0001'; end if;
  if em is null or em !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Please enter a valid email address.' using errcode = 'P0001'; end if;
  if ph !~ '^(\+?91)?[6-9]\d{9}$' then raise exception 'Please enter a valid 10-digit mobile number.' using errcode = 'P0001'; end if;
  if shop.txt(c->>'address_line1') is null or shop.txt(c->>'city') is null or shop.txt(c->>'state') is null then
    raise exception 'Please complete your delivery address.' using errcode = 'P0001';
  end if;
  if pin !~ '^\d{6}$' then raise exception 'Please enter a valid 6-digit PIN code.' using errcode = 'P0001'; end if;
  if pm = 'cod' and shop.setting('cod_enabled') <> '1' then raise exception 'Cash on Delivery is not available right now.' using errcode = 'P0001'; end if;
  if pm = 'upi' and shop.setting('upi_id') = '' then raise exception 'UPI payment is not available right now.' using errcode = 'P0001'; end if;
  if pm is null or pm not in ('cod', 'upi') then raise exception 'Please choose a payment method.' using errcode = 'P0001'; end if;

  -- Lock the products in this order so two shoppers can't buy the last unit at once.
  perform 1 from shop.products where id in (select (x->>'product_id')::bigint from jsonb_array_elements(coalesce(p->'items', '[]')) x) for update;

  quote := public.cart_quote(jsonb_build_object('items', p->'items', 'coupon', p->>'coupon'));
  if jsonb_array_length(quote->'lines') = 0 then raise exception 'Your bag is empty.' using errcode = 'P0001'; end if;
  if jsonb_array_length(quote->'notices') > 0 then
    raise exception '%', (select string_agg(x #>> '{}', ' ') from jsonb_array_elements(quote->'notices') x) using errcode = 'P0001';
  end if;
  if quote->>'coupon_error' is not null then raise exception '%', quote->>'coupon_error' using errcode = 'P0001'; end if;
  -- The quote clamps quantities; the shopper must see the final quantities before paying.
  for l in select * from jsonb_array_elements(quote->'lines') loop
    if exists (select 1 from jsonb_array_elements(p->'items') x
               where (x->>'product_id')::bigint = (l->>'product_id')::bigint
                 and (x->>'variant_id')::bigint is not distinct from (l->>'variant_id')::bigint
                 and coalesce((x->>'qty')::int, 1) <> (l->>'qty')::int) then
      raise exception 'Only % left of %. Please review your bag.', l->>'stock', l->>'name' using errcode = 'P0001';
    end if;
  end loop;

  shipping := (quote->>'shipping')::int + case when pm = 'cod' then shop.setting_int('cod_fee') else 0 end;
  insert into shop.orders (order_number, access_token, customer_id, name, email, phone, address_line1, address_line2, city, state,
      pincode, notes, subtotal, discount, shipping, total, coupon_code, payment_method, status)
  values ('TMP-' || tok, tok, auth.uid(), nm, em, ph, shop.txt(c->>'address_line1', 200), shop.txt(c->>'address_line2', 200),
      shop.txt(c->>'city', 100), shop.txt(c->>'state', 100), pin, shop.txt(c->>'notes', 1000),
      (quote->>'subtotal')::int, (quote->>'discount')::int, shipping,
      (quote->>'subtotal')::int - (quote->>'discount')::int + shipping, quote->>'coupon', pm,
      case when pm = 'cod' then 'confirmed' else 'pending' end)
  returning id into oid;
  onum := coalesce(nullif(shop.setting('order_prefix'), ''), 'KB') || '-' || (1000 + oid);
  update shop.orders set order_number = onum where id = oid;

  for l in select * from jsonb_array_elements(quote->'lines') loop
    if l->>'variant_id' is not null then
      update shop.product_variants set stock = stock - (l->>'qty')::int where id = (l->>'variant_id')::bigint and stock >= (l->>'qty')::int;
    else
      update shop.products set stock = stock - (l->>'qty')::int where id = (l->>'product_id')::bigint and stock >= (l->>'qty')::int;
    end if;
    get diagnostics n = row_count;
    if n <> 1 then raise exception 'Sorry, % just sold out. Please review your bag.', l->>'name' using errcode = 'P0001'; end if;
    insert into shop.order_items (order_id, product_id, variant_id, name, variant_name, sku, image, price, quantity, total)
    values (oid, (l->>'product_id')::bigint, (l->>'variant_id')::bigint, l->>'name', l->>'variant_name', l->>'sku', l->>'image',
      (l->>'price')::int, (l->>'qty')::int, (l->>'total')::int);
  end loop;

  if quote->>'coupon' is not null then
    update shop.coupons set used_count = used_count + 1 where lower(code) = lower(quote->>'coupon');
  end if;
  insert into shop.order_events (order_id, status, note) values (oid,
    case when pm = 'cod' then 'confirmed' else 'pending' end,
    case when pm = 'cod' then 'Order placed — Cash on Delivery' else 'Order placed — awaiting UPI payment' end);

  if auth.uid() is not null then
    update shop.customers set phone = coalesce(nullif(phone, ''), ph), address_line1 = shop.txt(c->>'address_line1', 200),
      address_line2 = shop.txt(c->>'address_line2', 200), city = shop.txt(c->>'city', 100), state = shop.txt(c->>'state', 100), pincode = pin
    where id = auth.uid();
  end if;
  return jsonb_build_object('order_number', onum, 'token', tok, 'total', (select total from shop.orders where id = oid));
end $$;

