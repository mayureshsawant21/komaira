  if cid is not null then
    select * into existing from shop.categories where id = cid;
    if not found then raise exception 'Category not found.' using errcode = 'P0001'; end if;
    cur := parent;
    for i in 1..50 loop
      exit when cur is null;
      if cur = cid then raise exception 'A category cannot be placed inside itself or one of its sub-categories.' using errcode = 'P0001'; end if;
      select parent_id into cur from shop.categories where id = cur;
    end loop;
    update shop.categories set name = nm,
      slug = case when slug_in is null or slug_in = existing.slug then existing.slug else shop.unique_slug('categories', slug_in, cid) end,
      description = shop.txt(p->>'description', 1000), image = shop.txt(p->>'image', 2000000), parent_id = parent,
      sort_order = coalesce((p->>'sort_order')::int, 0), is_active = coalesce((p->>'is_active')::boolean, true),
      show_on_home = coalesce((p->>'show_on_home')::boolean, true)
    where id = cid;
  else
    insert into shop.categories (name, slug, description, image, parent_id, sort_order, is_active, show_on_home)
    values (nm, shop.unique_slug('categories', coalesce(slug_in, nm)), shop.txt(p->>'description', 1000), shop.txt(p->>'image', 2000000), parent,
      coalesce((p->>'sort_order')::int, 0), coalesce((p->>'is_active')::boolean, true), coalesce((p->>'show_on_home')::boolean, true))
    returning id into cid;
  end if;
  return jsonb_build_object('id', cid, 'removed_image',
    case when existing.image is not null and existing.image is distinct from shop.txt(p->>'image', 2000000) then existing.image end);
end $$;

