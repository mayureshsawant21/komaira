-- p: { id, action: 'toggle' | 'up' | 'down' | 'delete' }
create or replace function public.admin_banner_action(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = shop, pg_temp as $$
declare bid bigint := (p->>'id')::bigint; ids bigint[]; i int; j int; tmp bigint; b shop.banners;
begin
  perform shop.require_admin();
  if p->>'action' = 'toggle' then
    update shop.banners set is_active = not is_active where id = bid;
  elsif p->>'action' = 'delete' then
    delete from shop.banners where id = bid returning * into b;
    return jsonb_build_object('removed_images', (select coalesce(jsonb_agg(x), '[]') from unnest(array[b.image, b.mobile_image]) x where x is not null));
  elsif p->>'action' in ('up', 'down') then
    select array_agg(id order by sort_order, id) into ids from shop.banners;
    i := array_position(ids, bid);
    j := case when p->>'action' = 'up' then i - 1 else i + 1 end;
    if i is not null and j between 1 and array_length(ids, 1) then
      tmp := ids[i]; ids[i] := ids[j]; ids[j] := tmp;
      for k in 1..array_length(ids, 1) loop update shop.banners set sort_order = k where id = ids[k]; end loop;
    end if;
  end if;
  return '{}';
end $$;

