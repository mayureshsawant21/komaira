-- =============================================================================
-- Komaira Boutique — database schema for Supabase
--
-- How to use: open your Supabase project → SQL Editor → New query → paste this
-- whole file → Run. Safe to run again later (it only creates what is missing
-- and replaces functions with their latest version).
--
-- Design: all tables live in the private "shop" schema, which the public API
-- cannot reach. The website talks to the database only through the functions
-- below, which check permissions (admin vs. shopper) and do all pricing, stock
-- and coupon maths on the server so prices cannot be tampered with.
-- Money is stored in paise (₹1 = 100).
-- =============================================================================

create schema if not exists shop;
revoke all on schema shop from public;

