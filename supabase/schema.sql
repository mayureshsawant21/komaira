-- p: { values: { key: value } } — only known keys are saved. Money keys are in paise.
create or replace function public.admin_save_settings(p jsonb) returns void
language plpgsql volatile security definer set search_path = shop, pg_temp as $$
declare k text; v text;
begin
  perform shop.require_admin();
  for k, v in select key, value #>> '{}' from jsonb_each(coalesce(p->'values', '{}')) loop
    if k not in ('store_name', 'tagline', 'contact_email', 'contact_phone', 'whatsapp', 'address', 'instagram', 'facebook', 'youtube',
                 'shipping_fee', 'free_shipping_threshold', 'cod_enabled', 'cod_fee', 'upi_id', 'upi_name', 'announcement_active',
                 'announcement_text', 'announcement_link', 'banner_autoplay_seconds', 'home_featured_title', 'home_new_title',
                 'promise_1', 'promise_2', 'promise_3', 'promise_4', 'meta_description', 'order_prefix', 'order_notify_email') then
      continue;
    end if;
    if k in ('shipping_fee', 'free_shipping_threshold', 'cod_fee', 'banner_autoplay_seconds') then
      v := coalesce(shop.paise(to_jsonb(v)), 0)::text;
    elsif k in ('instagram', 'facebook', 'youtube', 'announcement_link') then
      v := coalesce(shop.safe_link(v), '');
    elsif k = 'order_prefix' then
      v := coalesce(nullif(left(upper(regexp_replace(coalesce(v, ''), '[^A-Za-z0-9]', '', 'g')), 6), ''), 'KB');
    elsif k = 'store_name' then
      v := coalesce(shop.txt(v, 80), 'Komaira Boutique');
    else
      v := left(coalesce(v, ''), 1000);
    end if;
    insert into shop.settings (key, value) values (k, v) on conflict (key) do update set value = excluded.value;
  end loop;
end $$;

-- The person must already have signed up (or been added under Authentication → Users in Supabase).
create or replace function public.admin_add_admin(p jsonb) returns void
language plpgsql volatile security definer set search_path = shop, pg_temp as $$
declare u record;
begin
  perform shop.require_admin();
  select id, email into u from auth.users where lower(email) = lower(trim(coalesce(p->>'email', '')));
  if not found then
    raise exception 'No account with that email yet. Ask them to create an account on the store first (or add them under Authentication → Users in Supabase), then try again.' using errcode = 'P0001';
  end if;
  insert into shop.admins (user_id, name, email) values (u.id, coalesce(shop.txt(p->>'name', 100), u.email), u.email)
  on conflict (user_id) do update set name = excluded.name;
end $$;

